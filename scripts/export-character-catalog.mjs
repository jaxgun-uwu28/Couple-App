// Manifest is the only catalog source. This generates SQL data, never asset art.
import fs from 'node:fs';
import path from 'node:path';
const root='assets/characters/chibi_v1', file=`${root}/manifest.json`;
const m=JSON.parse(fs.readFileSync(file,'utf8'));
const roles={body:['body',''],blush:['body','blush'],hairBack:['hair_back',''],hairFront:['hair_front',''],face:['face',''],outfit:['outfit',''],accessories:['accessories','']};
const ids=new Set();const rows=[];
for(const l of m.layers){
 if(ids.has(l.id))throw Error(`Duplicate ID ${l.id}`);ids.add(l.id);
 const role=Object.entries(roles).find(([,v])=>v[0]===l.group&&(l.group!=='body'||(l.sub??[]).includes('blush')===(v[1]==='blush')))?.[0];
 if(!role)throw Error(`Unknown layer role ${l.id}`);
 if(l.file.includes('..')||path.isAbsolute(l.file))throw Error(`Unsafe file ${l.file}`);
 const b=fs.readFileSync(`${root}/half/${l.file}`);if(b.readUInt32BE(16)!==200||b.readUInt32BE(20)!==300||b[25]!==6)throw Error(`Invalid PNG canvas ${l.file}`);
 rows.push({id:l.id,role});
}
const look=m.default_config;if(!look)throw Error('Missing default_config');
for(const [role,value] of Object.entries(look))for(const id of Array.isArray(value)?value:value===null?[]:[value])if(!rows.some(r=>r.id===id&&r.role===role))throw Error(`Invalid default ${role}:${id}`);
const quote=s=>`'${s.replaceAll("'","''")}'`;
const sql=`-- Generated by scripts/export-character-catalog.mjs; edit the manifest, not this catalog.\ninsert into public.character_asset_options(id,role) values\n${rows.map(r=>`(${quote(r.id)},${quote(r.role)})`).join(',\n')}\non conflict(id) do update set role=excluded.role;\ninsert into public.character_asset_defaults(id,appearance) values(true,${quote(JSON.stringify(look))}::jsonb) on conflict(id) do update set appearance=excluded.appearance;\n`;
const target='supabase/migrations/20261003000400_character_catalog.sql';
if(process.argv.includes('--check')){if(fs.readFileSync(target,'utf8')!==sql)throw Error('Generated catalog is stale; run node scripts/export-character-catalog.mjs');}
else fs.writeFileSync(target,sql);
console.log(`Character manifest: ${rows.length} aligned layers; generated catalog ${process.argv.includes('--check')?'verified':'updated'}.`);
